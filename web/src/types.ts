export type Subject = "quant" | "aw" | "ielts_writing" | "ielts_reading" | "ielts_mock";
export type Mode = "tutor" | "solve";
export type MessageRole = "candidate" | "agent";

export interface Citation {
  index: number;
  text: string;
  source_uri: string;
  page_or_section: string;
  tier: "global" | "school" | "candidate";
}

// The independent answer check of a solved reply: a solver recomputed the problem from an equation
// the model wrote without seeing its answer. `solver` is what it computed, set when they disagree.
export type IndependentVerdict = "agrees" | "disagrees" | "not_checkable";

export interface IndependentCheck {
  verdict: IndependentVerdict;
  solver?: string;
}

export type ReplyStatus = "thinking" | "streaming" | "stopped" | "empty" | "failed";

export interface Message {
  id: string;
  role: MessageRole;
  content: string;
  citations?: Citation[];
  // Where an agent reply stands; absent once it finished normally. "thinking" and "streaming" mean
  // the turn is still running (see `isBusy`), the rest say how it ended.
  status?: ReplyStatus;
  // The reason, when status is "failed".
  error?: string;
  // Whether the math verifier accepted the final answer; absent when it did not run (tutor mode).
  mathVerified?: boolean;
  // Absent when the check did not run (tutor mode).
  independentCheck?: IndependentCheck;
  citation_stripped?: boolean;
  // "essay" when the reply is a sample essay: the bubble shows ESSAY_DISCLAIMER under it.
  disclaimer?: "essay";
  // The gateway's id for the turn that produced this reply; feedback is filed against it.
  traceId?: string;
  // The turn ran with the Calculator switch on: the reply arrives all at once, so while it
  // is "thinking" the bubble says the calculator is working.
  calculator?: boolean;
  vote?: "up" | "down";
  feedbackError?: string;
}

export interface Session {
  id: string;
  subject: Subject;
  mode: Mode;
}

export const ESSAY_DISCLAIMER =
  "This sample essay was generated by an AI tutor for study purposes only. Do not submit it as your own work.";

// What one reply cost and did, from GET /turns/{trace_id} (services/gateway/src/gateway/turns_api.py).
export interface TurnCall {
  source: "guardrails" | "agent";
  model: string | null;
  input_tokens: number;
  output_tokens: number;
  estimated: boolean;
  cost_usd: number;
  ms: number;
}

export interface TurnToolCall {
  name: string;
  ok: boolean;
  ms: number;
  round: number;
  // Blank (null) in tutor mode until the learner reveals them.
  arguments: string | null;
  result: string | null;
}

export type CalcVerdict = "agrees" | "differs" | "none";

export interface CalcCheck {
  verdict: CalcVerdict;
  answer: string;
  tool_value: string;
  tool: string;
}

export interface TurnView {
  trace_id: string;
  agent: string;
  mode: string;
  llm_calls: number;
  input_tokens: number;
  output_tokens: number;
  estimated: boolean;
  cost_usd: number;
  total_ms: number | null;
  calls: TurnCall[];
  math_tools: boolean;
  tool_calls: TurnToolCall[];
  tools_hidden: boolean;
  calc_check: CalcCheck | null;
}
